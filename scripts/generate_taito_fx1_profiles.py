#!/usr/bin/env python3
"""Embed all 22 pinned Taito profiles and source ROM CRC/layout checks."""
import argparse
import json
from pathlib import Path
import prepare_mame_psx as mame
import taito_fx1_boards as registry

ROOT = Path(__file__).resolve().parents[1]
KEYS = ['format', 'mame_set', 'mame_parent', 'bios_parent', 'board_type', 'board_model',
        'mame_machine', 'mame_input', 'cpu_device', 'cpu_clock_hz', 'gpu_device',
        'gpu_clock_hz', 'main_ram_size', 'vram_size', 'sound_cpu_device',
        'sound_cpu_clock_hz', 'sound_device', 'sound_clock_hz', 'sound_latch_device',
        'watchdog_device', 'bank_select_register', 'bank_select_mask',
        'watchdog_clock_bit', 'sample_region', 'board_execution_verified']
TAGS = ['maincpu:rom', 'bankedroms', 'audiocpu', 'ym2610b:adpcma', 'cat702_1', 'cat702_2']

def generate(source):
    document = registry.build_registry(source)
    assert len(document['profiles']) == 22
    assert sum(p['runtime_candidate'] for p in document['profiles']) == 21
    output = ['/* Generated by scripts/generate_taito_fx1_profiles.py.',
              ' * MAME ' + registry.COMMIT + '; original source BSD-3-Clause, smf/Philip Bennett. */',
              'static const char *const config_keys[] = {' + ', '.join(json.dumps(k) for k in KEYS) + '};']
    rows = []
    for p in document['profiles']:
        name = p['set']; eligible = p['runtime_candidate']
        vals = ['pcsx-aow-taito-fx1-v1', name, p.get('parent') or 'none',
                p.get('bios_parent') or 'none', p['board_type'], p['board_model'],
                p['machine'], p['input']]
        vals += [str(p.get(k, 'none')) for k in KEYS[8:20]]
        vals += [hex(p.get('bank_select_register', 0)),
                 f"{p.get('bank_select_mask', 0):#04x}",
                 str(p.get('watchdog_clock_bit', 'none')), p.get('sample_region', 'none'), 'false']
        assert len(vals) == len(KEYS)
        sizes = [0] * 6; erase = [0] * 6; checks = []
        if eligible:
            romset, _, _ = mame._find_romset(source, name)
            tags = TAGS if p["board_type"] == "FX1S" else ["maincpu:rom", "bankedroms", "taito_zoom:mn10200", "taito_zoom:zsg2", "cat702_1", "cat702_2"]
            for i, tag in enumerate(tags):
                region = romset.regions[tag]; sizes[i] = region.size; erase[i] = region.erase
                for op in region.operations:
                    if not isinstance(op, mame.LoadOp):
                        raise ValueError(f'{name}/{tag}: unsupported source assembly operation {op}')
                    spec = next(f for f in romset.files if f.index == op.file_index)
                    assert op.source_offset == 0 and op.length == spec.expected_size and spec.status == 'good'
                    checks.append(f'{{{i}, {op.offset:#x}, {op.length:#x}, {op.group}, {op.stride}, {int(op.swap)}, 0x{spec.crc32}u}}')
            output += [f'static const MediaCheck media_{name}[] = {{', ',\n'.join(checks), '};']
        rows.append('{{' + ', '.join(json.dumps(v) for v in vals) + '}, ' + str(int(eligible)) +
                    ', {' + ', '.join(hex(v) for v in sizes) + '}, {' + ', '.join(str(v) for v in erase) +
                    '}, ' + (f'media_{name}, sizeof(media_{name}) / sizeof(media_{name}[0])' if eligible else 'NULL, 0') + '}')
    output += ['static const Profile profiles[] = {', ',\n'.join(rows), '};', '']
    return '\n'.join(output)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=registry.DEFAULT_SOURCE)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'libpcsxcore/arcade/taito_fx1_profiles.inc'
    text = generate(args.source)
    if args.check:
        if path.read_text() != text:
            raise SystemExit('Taito FX1 native profiles are stale')
    else:
        path.write_text(text)
