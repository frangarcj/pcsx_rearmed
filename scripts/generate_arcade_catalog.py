#!/usr/bin/env python3
"""Embed supported prepared profiles in the Vita/Mac game shelf (no media)."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'frontend/arcade_catalog_profiles.inc'


def generate():
    inventory = json.loads((ROOT / 'scripts/mame_psx_systems.json').read_text())
    descriptions = {r['set']: r['description'] for s in inventory['systems'] for r in s['sets']}
    lines = ['/* Generated by scripts/generate_arcade_catalog.py; do not edit. */']
    families = [
        ('system12', 'Namco System 12', 'ARCADE_PROFILE_SYSTEM12', 'sets'),
        ('system10', 'Namco System 10', 'ARCADE_PROFILE_SYSTEM10', 'profiles'),
        ('system11', 'Namco System 11', 'ARCADE_PROFILE_SYSTEM11', 'profiles'),
        ('capcom_zn', 'Capcom ZN', 'ARCADE_PROFILE_CAPCOM_ZN', 'profiles'),
    ]
    for family, title, kind, key in families:
        doc = json.loads((ROOT / f'scripts/{family}_boards.json').read_text())
        assert doc['mame_source_commit'] == inventory['source']['mame_commit']
        for row in doc[key]:
            if family in ('system10', 'capcom_zn') and not row['runtime_candidate']:
                continue
            name, parent = row['set'], row.get('parent') or ''
            if family == 'system10':
                files = ['main.bin', 'rawflash.bin', 'datarom.bin'] if row['board_type'] == 'MEM(M)' else [
                    'main.bin', *('raw' + r['tag'] + '.bin' for r in row['rom_regions'] if r['tag'].startswith('nand'))]
            elif family == 'system11':
                files = ['main.bin', 'banked.bin', 'c76.bin', 'c76bios.bin', 'wave.bin']
            elif family == 'capcom_zn':
                files = ['main.bin', 'banked.bin', 'country.bin', 'audiocpu.bin', 'qsound_samples.bin',
                         'qsound_dsp.bin', 'cat702_key0.bin', 'cat702_key1.bin']
            else:
                files = ['main.bin', 'banked.bin', 'sub.bin', 'wave.bin']
            values = [title, name, parent, descriptions[name], descriptions.get(parent, descriptions[name]), '|'.join(files)]
            lines.append('{' + kind + ', ' + ', '.join(json.dumps(v) for v in values) + f", {int(row['year'])}" + '},')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != result:
            raise SystemExit('arcade_catalog_profiles.inc is stale; run scripts/generate_arcade_catalog.py')
    else:
        OUTPUT.write_text(result)
