#!/usr/bin/env python3
"""Embed the System 12 MAME romsets for the native zip loader.

Reads the ROM declarations of namco/namcos12.cpp at the pinned MAME commit
(through prepare_mame_psx.py's parser) and the board registry, and writes
libpcsxcore/arcade/system12_romsets.inc: for each set, its board profile,
its ROM files (size, CRC32) and how each file is placed in the four board
regions. The loader then builds the regions from MAME zips on the console.

  generate_system12_romsets.py --mame-source ../mamedev
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import subprocess
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
import prepare_mame_psx as mame  # noqa: E402

DRIVER = "namco/namcos12.cpp"
REGIONS = ("maincpu:rom", "bankedroms", "sub", "c352")
OUTPUT = ROOT / "libpcsxcore/arcade/system12_romsets.inc"


def c_string(value: str) -> str:
    return json.dumps(value)


def generate(source: Path) -> str:
    commit = subprocess.run(["git", "-C", str(source), "rev-parse", "HEAD"], check=True,
                            capture_output=True, text=True).stdout.strip()
    if commit != mame.PINNED_MAME_COMMIT:
        raise SystemExit(f"MAME source is at {commit}, not the pinned {mame.PINNED_MAME_COMMIT}")
    registry = json.loads((HERE / "system12_boards.json").read_text(encoding="utf-8"))
    if registry["mame_source_commit"] != commit:
        raise SystemExit("system12_boards.json is not from the pinned MAME commit")
    parsed, parents, _ = mame.parse_driver((source / "src/mame" / DRIVER).read_text(encoding="utf-8"), DRIVER)

    files: list[str] = []
    ops: list[str] = []
    sets: list[str] = []
    for profile in registry["sets"]:
        name = profile["set"]
        romset = parsed[name]
        if romset.bios:
            raise SystemExit(f"{name}: System 12 sets have no BIOS selection")
        if (parents.get(name) or None) != profile["parent"]:
            raise SystemExit(f"{name}: parent differs between MAME and the registry")
        unsupported = list(profile["unsupported"])
        # A file without a dump has no CRC to find it by.
        if any(spec.crc32 is None for spec in romset.files):
            unsupported.append("undumped_rom")
        first_file, first_op = len(files), len(ops)
        used: dict[int, int] = {}
        sizes = []
        for region_index, tag in enumerate(REGIONS):
            region = romset.regions[tag]
            if region.erase != 0:
                raise SystemExit(f"{name}: region {tag} is not erased to zero")
            sizes.append(region.size)
            for op in region.operations:
                if isinstance(op, mame.LoadOp):
                    spec = romset.files[op.file_index]
                    if spec.crc32 is None:
                        continue
                    if op.file_index not in used:
                        used[op.file_index] = len(files) - first_file
                        files.append(f"    {{{c_string(spec.filename)}, 0x{spec.expected_size:x}, 0x{spec.crc32}}},")
                    ops.append(f"    {{{region_index}, S12_LOAD, {used[op.file_index]}, 0x{op.source_offset:x}, "
                               f"0x{op.offset:x}, 0x{op.length:x}, {op.group}, {op.stride}, "
                               f"{1 if op.swap else 0}, 0}},")
                elif isinstance(op, mame.FillOp):
                    ops.append(f"    {{{region_index}, S12_FILL, 0, 0, 0x{op.offset:x}, 0x{op.length:x}, "
                               f"1, 1, 0, 0x{op.value:02x}}},")
                else:
                    raise SystemExit(f"{name}: unsupported ROM operation {type(op).__name__} in {tag}")
        info = "{" + ", ".join([c_string(name), c_string(profile["parent"] or ""),
                                c_string(profile["description"]),
                                c_string(",".join(unsupported) or "none"), str(profile["year"])]) + "}"
        sets.append("    {" + ", ".join([
            info, c_string(profile["machine"]), c_string(profile["state"]),
            f"0x{profile['ram_size']:x}", str(int(profile["boot_hack"])), str(int(profile["alt_bank"])),
            str(int(profile["tektagt_dma"])),
            "{" + ", ".join(f"0x{size:x}" for size in sizes) + "}",
            str(first_file), str(len(files) - first_file), str(first_op), str(len(ops) - first_op),
        ]) + "},")
    return "\n".join([
        f"/* Generated by scripts/generate_system12_romsets.py from MAME {commit[:8]}"
        f" ({DRIVER}) and scripts/system12_boards.json; do not edit. */",
        "static const s12_rom_file s12_files[] = {", *files, "};",
        "static const s12_rom_op s12_ops[] = {", *ops, "};",
        "static const s12_romset s12_sets[] = {", *sets, "};",
        "",
    ])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--mame-source", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    args.output.write_text(generate(args.mame_source), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
