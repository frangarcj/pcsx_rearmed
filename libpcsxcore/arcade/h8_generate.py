"""Generate standalone H8/300H instructions from MAME's BSD opcode source."""
from pathlib import Path
import io
import re
from h8_mame_make import OpcodeList, save_full_one, save_partial_one, has_memory, has_eat
root = Path(__file__).resolve().parent
ops = OpcodeList(str(root / 'h8_mame.lst'), 1)
ops.states_info = [s for s in ops.states_info if s.enabled and s.name in ('reset', 'irq')]
ops.build_dispatch()
f = io.StringIO()
f.write('// license:BSD-3-Clause\n// copyright-holders:Olivier Galibert\n// Generated by h8_generate.py; do not edit.\n')
names = []
for op in ops.opcode_info:
    if not op.enabled:
        continue
    name = op.function_name()
    names.append(name + '_full')
    names.append(name + '_partial')
    body = op.source
    if op.name == 'sleep':
        body = ['\tm_NPC = m_PC & 0xffffff;', '\tm_PIR = read16i(m_PC);',
                '\tm_PC += 2;', '\tm_sleeping = true;', '\tprefetch_done();']
    save_full_one(f, 'H8CPU', name, body)
    save_partial_one(f, 'H8CPU', name, body)
for s in ops.states_info:
    name = 'state_' + s.name
    names.extend((name + '_full', name + '_partial'))
    save_full_one(f, 'H8CPU', name, s.source)
    save_partial_one(f, 'H8CPU', name, s.source)
for dsp in ops.dispatch_info:
    if dsp.enabled:
        name = 'dispatch_' + dsp.name
        names.extend((name + '_full', name + '_partial'))
        save_full_one(f, 'H8CPU', name, dsp.source())
        save_partial_one(f, 'H8CPU', name, dsp.source())
ops.save_exec(f, 'H8CPU', 1, 'full')
ops.save_exec(f, 'H8CPU', 1, 'partial')
source=f.getvalue()
# Keep the historical complete-state scheduler behavior while enabling the
# generated MAME deadline checkpoints only in h8_run_until().
source=source.replace('if(m_icount <= m_bcount) {',
                      'if(deadline_run && m_icount <= m_bcount) {')
# Promote before shifting a 16-bit word; C++ integral promotion is signed int.
source=re.sub(r'(m_IR\[\d+\]) << 16',r'u32(\1) << 16',source)
source=re.sub(r'(read16i?\([^()\n]*\)) << 16',r'u32(\1) << 16',source)
root.joinpath('h8_instructions.inc').write_text(source)
# Table dispatch for first-level opcodes: the same switch as do_exec_full(),
# returning a thunk for the handler it would call instead of calling it.
start=source.index('void H8CPU::do_exec_full()\n{')
end=source.index('void H8CPU::do_exec_partial()')
full=source[start:end].rstrip()
handlers=sorted(set(re.findall(r'\b(\w+)\(\);',full)))
resolver=full.replace('void H8CPU::do_exec_full()','H8CPU::Thunk H8CPU::resolve_full(u32 state)',1)
resolver=resolver.replace('m_inst_state','state')
resolver=re.sub(r'\b(\w+)\(\);',r'return &thunk_\1;',resolver)
assert resolver.endswith('}')
resolver=resolver[:-1]+'\treturn nullptr;\n}\n'
dispatch=['// Generated by h8_generate.py from do_exec_full(); do not edit.\n']
dispatch+=['static void thunk_%s(H8CPU *c) { c->%s(); }\n' % (h,h) for h in handlers]
dispatch.append(resolver)
root.joinpath('h8_dispatch.inc').write_text(''.join(dispatch))
root.joinpath('h8_declarations.inc').write_text('// Generated by h8_generate.py.\n' + ''.join('void '+n+'();\n' for n in names))

# h8_fast.inc: the same full-state bodies for h8_fast_run(), which keeps the
# CPU state in a local H8Fast `f`. Bodies that use only that state, the bus
# and the arithmetic helpers become labels; the others (CCR loads that refilter
# IRQs, rte, trapa, sleep, eepmov, divides), the reset/IRQ states and illegal
# encodings run the original handlers through `slow`. Checkpoints keep their
# substate numbers, so `suspend` leaves a state the partial handlers resume.
FAST_STATE = {'m_NPC', 'm_PC', 'm_PIR', 'm_IR', 'm_TMP1', 'm_TMP2', 'm_CCR',
              'm_inst_state', 'm_mode_advanced', 'm_has_mac', 'm_has_hc',
              'read16i', 'read16', 'read8', 'write8', 'write16', 'internal',
              'r32_r', 'r32_w', 'r16_r', 'r16_w', 'r8_r', 'r8_w', 'prefetch_switch'}
FAST_OTHER = {'prefetch_done', 'prefetch_done_noirq', 'if', 'else', 'true', 'false',
              'int', 's8', 's16', 's32', 's64', 'u8', 'u16', 'u32', 'u64'}
def fast_tokens(lines):
    code = '\n'.join(re.sub(r'//.*', '', l) for l in lines)
    return set(re.findall(r'\b[A-Za-z_]\w*\b', code))
def fast_eligible(lines):
    if any(has_eat(l) for l in lines):
        return False
    return all(t in FAST_STATE or t in FAST_OTHER or re.match(r'(F_|set_|do_)', t)
               for t in fast_tokens(lines))
def fast_line(line):
    line = re.sub(r'//.*', '', line)
    line = re.sub(r'(?<![.\w>:])\b(F_\w+)\b', r'H8CPU::\1', line)
    return re.sub(r'(?<![.\w>:])\b(m_\w+|read16i|read16|read8|write8|write16|internal|'
                  r'r32_r|r32_w|r16_r|r16_w|r8_r|r8_w|prefetch_switch|set_\w+|do_\w+)\b',
                  r'f.\1', line)
def fast_body(lines, dispatch):
    out = []
    substate = 1
    for line in lines:
        if line.strip() == 'prefetch_done();':
            out.append('\tgoto fetch_next;')
        elif line.strip() == 'prefetch_done_noirq();':
            out.append('\tgoto fetch_next_noirq;')
        else:
            out.append(fast_line(line))
            if has_memory(line):
                out.append('\tif(f.m_icount <= f.m_bcount) { cpu->m_inst_substate = %d; goto suspend; }' % (substate+1))
                substate += 2
    if dispatch:
        out.append('\tgoto second_level;')
    else:
        assert sum(l.count('prefetch_done') for l in lines) == 1, lines
    return out
fast = []  # (name, lines, is_dispatch)
for op in ops.opcode_info:
    if op.enabled and op.name != 'sleep' and fast_eligible(op.source):
        fast.append((op.function_name(), op.source, False))
for dsp in ops.dispatch_info:
    if dsp.enabled:
        fast.append(('dispatch_' + dsp.name, dsp.source(), True))
fast_names = {n for n, _, _ in fast}
def fast_switch(target_of):
    text = full[full.index('{')+1:full.rindex('}')]
    def call(m):
        return target_of(m.group(1) if m.group(1) in fast_names else None)
    text = re.sub(r'\b(\w+)_full\(\);', call, text)
    return text.replace('illegal();', target_of(None))
f = ['// Generated by h8_generate.py; do not edit.\n']
f.append('#if defined(H8_FAST_DECLARATIONS)\n')
for line in root.joinpath('h8_arithmetic_declarations.inc').read_text().splitlines():
    if line.strip() and not line.startswith('//'):
        f.append('__attribute__((always_inline)) inline ' + line + '\n')
f.append('#elif defined(H8_FAST_INDEX)\n')
f.append('enum {\n' + ''.join('\tFI_%s,\n' % n for n, _, _ in fast) + '\tFI_SLOW\n};\n')
f.append('static unsigned h8_fast_index(u32 state)\n{')
f.append(fast_switch(lambda n: 'return FI_%s;' % n if n else 'return FI_SLOW;').replace('m_inst_state', 'state'))
f.append('\treturn FI_SLOW;\n}\n')
f.append('#elif defined(H8_FAST_LABELS)\n')
f.append(''.join('\t&&L_%s,\n' % n for n, _, _ in fast) + '\t&&slow_first,\n')
f.append('#elif defined(H8_FAST_BODIES)\n')
for n, lines, dispatch in fast:
    f.append('L_%s:\n\tH8_FAST_COUNT;\nB_%s: {\n' % (n, n))
    f.append(''.join(l + '\n' for l in fast_body(lines, dispatch)))
    f.append('}\n')
f.append('second_level: {')
f.append(fast_switch(lambda n: 'goto B_%s;' % n if n else 'goto slow;').replace('m_inst_state', 'f.m_inst_state'))
f.append('\tgoto slow;\n}\n')
f.append('#endif\n')
root.joinpath('h8_fast.inc').write_text(''.join(f))
