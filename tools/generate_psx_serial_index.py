#!/usr/bin/env python3
import argparse
import pathlib
import re

FNV_OFFSET = 0xCBF29CE484222325
FNV_PRIME = 0x100000001B3


def ascii_lower_bytes(text):
    data = bytearray(text.encode("utf-8"))
    for i, value in enumerate(data):
        if 0x41 <= value <= 0x5A:
            data[i] = value + 0x20
    return bytes(data)


def title_root(title):
    marker = title.find(" (")
    root = title if marker < 0 else title[:marker]
    dash = root.find(" - ")
    if 0 < dash <= 5:
        prefix = root[:dash]
        if all(("A" <= c <= "Z") or ("0" <= c <= "9") for c in prefix):
            root = root[dash + 3 :]
    return root


def fnv1a64(text):
    value = FNV_OFFSET
    for byte in ascii_lower_bytes(title_root(text)):
        value ^= byte
        value = (value * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
    return value


def normalize_serial(serial):
    return "".join(c for c in serial.upper() if c.isalnum())[:9]


def parse_dat(path):
    text = pathlib.Path(path).read_text(encoding="utf-8", errors="replace")
    blocks = re.findall(r"(?ms)^game \((.*?)^\)", text)
    entries = {}
    for block in blocks:
        name = re.search(r'(?m)^\s*name "(.*?)"', block)
        serial = re.search(r'(?m)^\s*serial "([^"]+)"', block)
        if not name or not serial:
            continue
        key = normalize_serial(serial.group(1))
        if len(key) < 8:
            continue
        entries.setdefault(key, fnv1a64(name.group(1)))
    return sorted(entries.items())


def write_include(entries, path):
    out = [
        "/* Generated by tools/generate_psx_serial_index.py. */",
        "static const PsxSerialTitleHash k_psx_serial_title_hashes[] = {",
    ]
    for serial, title_hash in entries:
        out.append('    {"%s", 0x%016XULL},' % (serial, title_hash))
    out.append("};")
    out.append("")
    pathlib.Path(path).write_text("\n".join(out), encoding="ascii")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("dat", help="libretro-database/Redump Sony - PlayStation DAT")
    parser.add_argument("output", help="generated .inc path")
    args = parser.parse_args()
    entries = parse_dat(args.dat)
    write_include(entries, args.output)
    print("wrote %d serials to %s" % (len(entries), args.output))


if __name__ == "__main__":
    main()
